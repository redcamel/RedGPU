import RedGPUObject from '../../../base/RedGPUObject';
import RedGPUContext from '../../../context/RedGPUContext';

/**
 * [KO] 스캐터 컴퓨트 컬링 워크그룹의 기본 크기 (`64`)입니다.
 * [EN] Default workgroup size (`64`) for scatter compute culling.
 *
 * @category Landscape
 */
export const CULLING_WORKGROUP_SIZE = 64;

/**
 * [KO] `drawIndexedIndirect` 명령 슬롯당 `Uint32` 인자 개수 (`5`)입니다.
 * [EN] Number of `Uint32` arguments (`5`) per `drawIndexedIndirect` command slot.
 *
 * @category Landscape
 */
export const DRAW_INDEXED_INDIRECT_ARGS_COUNT = 5;

/**
 * [KO] WGSL 셰이더 리플렉션을 통해 인스턴스 및 타입 파라미터 구조체 크기를 추출하기 위한 설정 인터페이스입니다.
 * [EN] Configuration interface for extracting instance and type parameter struct sizes via WGSL shader reflection.
 *
 * @category Landscape
 */
export interface ScatterShaderReflectionConfig {
    /**
     * [KO] WGSL 파서에서 생성된 셰이더 리플렉션 정보 객체
     * [EN] Shader reflection info object generated by the WGSL parser
     */
    shaderInfo: any;
    /**
     * [KO] 인스턴스 데이터 구조체의 WGSL 식별자 이름
     * [EN] WGSL identifier name of the instance data struct
     */
    instanceStructName: string;
    /**
     * [KO] 타입별 파라미터 구조체의 WGSL 식별자 이름 (선택적)
     * [EN] WGSL identifier name of the per-type parameter struct (optional)
     */
    typeParamStructName?: string;
}

/**
 * [KO] 메가 버퍼 내에서 단일 스캐터 타입에 할당된 세그먼트 오프셋 및 용량 정보를 담는 인터페이스입니다.
 * [EN] Interface containing segment offsets and capacity information allocated to a single scatter type within the mega buffer.
 *
 * @category Landscape
 */
export interface ScatterBaseSegmentAllocation {
    /**
     * [KO] 할당된 스캐터 타입의 숫자 ID
     * [EN] Numeric ID of the allocated scatter type
     */
    typeId: number;
    /**
     * [KO] 할당된 스캐터 타입의 이름 (선택적)
     * [EN] Name of the allocated scatter type (optional)
     */
    name?: string;
    /**
     * [KO] 워크그룹 크기로 정렬된 최대 인스턴스 수용 개수
     * [EN] Maximum instance capacity aligned to the workgroup size
     */
    maxInstances: number;
    /**
     * [KO] 원시(Raw) 인스턴스 버퍼 내 시작 인스턴스 오프셋
     * [EN] Starting instance offset within the raw instance buffer
     */
    rawBaseOffset: number;
    /**
     * [KO] 컬링된(Culled) 인스턴스 버퍼 내 시작 인스턴스 오프셋
     * [EN] Starting instance offset within the culled instance buffer
     */
    culledBaseOffset: number;
    /**
     * [KO] 인다이렉트 드로우 버퍼 내 시작 슬롯 오프셋
     * [EN] Starting slot offset within the indirect draw buffer
     */
    indirectBaseOffset: number;
    /**
     * [KO] 이 세그먼트가 사용하는 렌더 유닛(서브메시/LOD) 슬롯 개수
     * [EN] Number of render unit (submesh/LOD) slots used by this segment
     */
    renderUnitCount: number;
    /**
     * [KO] 현재 실제로 활성화된 인스턴스 개수
     * [EN] Number of currently active instances
     */
    instanceCount: number;
}

/**
 * [KO] 스캐터 시스템의 원시 인스턴스 버퍼, 컬링 결과 버퍼, 타입 파라미터 버퍼 및 인다이렉트 드로우 버퍼를 통합 관리하는 추상 메가 버퍼 클래스입니다.
 * [EN] Abstract mega buffer class that centrally manages the raw instance buffer, culled result buffer, type parameter buffer, and indirect draw buffer for the scatter system.
 *
 * ::: warning
 * [KO] 이 클래스는 추상 클래스이므로 직접 인스턴스를 생성할 수 없습니다.<br/>'new' 키워드를 사용하여 직접 인스턴스를 생성하지 마십시오.
 * [EN] This class is an abstract class, so you cannot create an instance directly.<br/>Do not create an instance directly using the 'new' keyword.
 * :::
 *
 * @category Landscape
 */
abstract class AScatterMegaBuffer extends RedGPUObject {
    #instanceCapacity: number;
    #strideFloats: number;
    #strideBytes: number;
    #typeParamFloats: number;
    #maxRenderUnits: number;
    #maxTypes: number;

    #totalAllocatedInstances: number = 0;
    #totalAllocatedCulledInstances: number = 0;
    #totalIndirectDrawCalls: number = 0;

    #cpuTypeParamsBuffer: Float32Array;
    #cpuTypeParamsUint32: Uint32Array;

    #rawGPUBuffer: GPUBuffer | null = null;
    #culledGPUBuffer: GPUBuffer | null = null;
    #indirectGPUBuffer: GPUBuffer | null = null;
    #typeParamsGPUBuffer: GPUBuffer | null = null;

    #indirectResetTemplate: Uint32Array;
    #indirectResetTemplateGPUBuffer: GPUBuffer | null = null;

    #onRecreated: (() => void) | null = null;

    /**
     * [KO] AScatterMegaBuffer 인스턴스를 초기화하고 기본 GPU 버퍼들을 생성합니다.
     * [EN] Initializes an AScatterMegaBuffer instance and creates the base GPU buffers.
     *
     * @param redGPUContext -
     * [KO] RedGPU 컨텍스트 인스턴스
     * [EN] RedGPUContext instance
     * @param reflectionConfig -
     * [KO] 구조체 크기 추출을 위한 셰이더 리플렉션 설정
     * [EN] Shader reflection configuration for extracting struct sizes
     * @param initialCapacity -
     * [KO] 초기 확보할 인스턴스 수용량
     * [EN] Initial instance capacity to allocate
     * @param maxTypes -
     * [KO] 지원할 최대 스캐터 타입 수
     * [EN] Maximum number of scatter types to support
     * @param maxRenderUnits -
     * [KO] 지원할 최대 인다이렉트 렌더 유닛 슬롯 수
     * [EN] Maximum number of indirect render unit slots to support
     * @throws
     * [KO] 셰이더 리플렉션에서 인스턴스 또는 타입 파라미터 구조체 크기를 찾지 못한 경우 `Error` 발생
     * [EN] Throws `Error` if instance or type parameter struct sizes cannot be reflected from shader info
     */
    constructor(
        redGPUContext: RedGPUContext,
        reflectionConfig: ScatterShaderReflectionConfig,
        initialCapacity: number,
        maxTypes: number,
        maxRenderUnits: number
    ) {
        super(redGPUContext);

        const {shaderInfo, instanceStructName, typeParamStructName} = reflectionConfig;
        const {structs} = shaderInfo;

        const strideBytes = structs[instanceStructName]?.arrayBufferByteLength;

        if (!strideBytes) {
            throw new Error(`[AScatterMegaBuffer] Failed to reflect instance stride for "${instanceStructName}".`);
        }

        const typeParamBytes = typeParamStructName
            ? structs[typeParamStructName]?.arrayBufferByteLength
            : 0;

        if (typeParamStructName && !typeParamBytes) {
            throw new Error(`[AScatterMegaBuffer] Failed to reflect type param struct size for "${typeParamStructName}".`);
        }

        this.#maxTypes = maxTypes;
        this.#maxRenderUnits = maxRenderUnits;
        this.#strideBytes = strideBytes;
        this.#strideFloats = strideBytes / Float32Array.BYTES_PER_ELEMENT;
        this.#typeParamFloats = typeParamBytes / Float32Array.BYTES_PER_ELEMENT;

        this.#instanceCapacity = Math.ceil(initialCapacity / CULLING_WORKGROUP_SIZE) * CULLING_WORKGROUP_SIZE;

        const typeParamsCount = this.#maxTypes * this.#typeParamFloats;
        this.#cpuTypeParamsBuffer = new Float32Array(typeParamsCount > 0 ? typeParamsCount : 1);
        this.#cpuTypeParamsUint32 = new Uint32Array(this.#cpuTypeParamsBuffer.buffer);

        this.#indirectResetTemplate = new Uint32Array(this.#maxRenderUnits * DRAW_INDEXED_INDIRECT_ARGS_COUNT);

        this.#initBaseBuffers();
    }

    /**
     * [KO] 단일 인스턴스 데이터의 바이트 단위 스트라이드 크기를 반환합니다.
     * [EN] Returns the stride size in bytes for a single instance data entry.
     */
    get strideBytes(): number {
        return this.#strideBytes;
    }

    /**
     * [KO] 단일 인스턴스 데이터의 `Float32` 요소 개수를 반환합니다.
     * [EN] Returns the number of `Float32` elements for a single instance data entry.
     */
    get strideFloats(): number {
        return this.#strideFloats;
    }

    /**
     * [KO] 단일 타입 파라미터 구조체의 `Float32` 요소 개수를 반환합니다.
     * [EN] Returns the number of `Float32` elements for a single type parameter struct.
     */
    get typeParamFloats(): number {
        return this.#typeParamFloats;
    }

    /**
     * [KO] 메가 버퍼가 지원하는 최대 렌더 유닛 슬롯 수를 반환합니다.
     * [EN] Returns the maximum number of render unit slots supported by the mega buffer.
     */
    get maxRenderUnits(): number {
        return this.#maxRenderUnits;
    }

    /**
     * [KO] 메가 버퍼가 지원하는 최대 스캐터 타입 수를 반환합니다.
     * [EN] Returns the maximum number of scatter types supported by the mega buffer.
     */
    get maxTypes(): number {
        return this.#maxTypes;
    }

    /**
     * [KO] 현재 할당된 최대 인스턴스 수용량(Capacity)을 반환합니다.
     * [EN] Returns the currently allocated maximum instance capacity.
     */
    get instanceCapacity(): number {
        return this.#instanceCapacity;
    }

    /**
     * [KO] CPU 측 타입 파라미터 `Float32Array` 버퍼를 반환합니다.
     * [EN] Returns the CPU-side type parameter `Float32Array` buffer.
     */
    get cpuTypeParamsBuffer(): Float32Array {
        return this.#cpuTypeParamsBuffer;
    }

    /**
     * [KO] CPU 측 타입 파라미터 버퍼의 `Uint32Array` 뷰를 반환합니다.
     * [EN] Returns the `Uint32Array` view of the CPU-side type parameter buffer.
     */
    get cpuTypeParamsUint32(): Uint32Array {
        return this.#cpuTypeParamsUint32;
    }

    /**
     * [KO] 필수 GPU 버퍼(원시 버퍼 및 인다이렉트 버퍼)가 모두 생성되어 준비되었는지 여부를 반환합니다.
     * [EN] Returns whether the essential GPU buffers (raw buffer and indirect buffer) are created and ready.
     */
    get isReady(): boolean {
        return this.#rawGPUBuffer != null && this.#indirectGPUBuffer != null;
    }

    /**
     * [KO] 베이킹된 원시(Raw) 인스턴스 데이터를 보관하는 GPU 버퍼를 반환합니다.
     * [EN] Returns the GPU buffer holding baked raw instance data.
     */
    get rawGPUBuffer(): GPUBuffer | null {
        return this.#rawGPUBuffer;
    }

    /**
     * [KO] 메인 패스 컬링 결과 인스턴스 데이터를 보관하는 GPU 버퍼를 반환하거나 설정합니다.
     * [EN] Gets or sets the GPU buffer holding culled instance data for the main pass.
     */
    get culledGPUBuffer(): GPUBuffer | null {
        return this.#culledGPUBuffer;
    }

    set culledGPUBuffer(buffer: GPUBuffer | null) {
        this.#culledGPUBuffer = buffer;
    }

    /**
     * [KO] 메인 패스 `drawIndexedIndirect` 명령 인자들을 보관하는 GPU 버퍼를 반환합니다.
     * [EN] Returns the GPU buffer holding `drawIndexedIndirect` command arguments for the main pass.
     */
    get indirectGPUBuffer(): GPUBuffer | null {
        return this.#indirectGPUBuffer;
    }

    /**
     * [KO] 타입별 컬링 파라미터를 보관하는 GPU 버퍼를 반환합니다.
     * [EN] Returns the GPU buffer holding per-type culling parameters.
     */
    get typeParamsGPUBuffer(): GPUBuffer | null {
        return this.#typeParamsGPUBuffer;
    }

    /**
     * [KO] 용량 확장으로 인해 GPU 버퍼가 재생성되었을 때 호출되는 콜백 함수를 반환하거나 설정합니다.
     * [EN] Gets or sets the callback function invoked when GPU buffers are recreated due to capacity expansion.
     */
    get onRecreated(): (() => void) | null {
        return this.#onRecreated;
    }

    set onRecreated(cb: (() => void) | null) {
        this.#onRecreated = cb;
    }

    /**
     * [KO] 현재까지 세그먼트로 할당된 총 원시 인스턴스 수를 반환합니다.
     * [EN] Returns the total number of raw instances allocated across segments so far.
     */
    get totalAllocatedInstances(): number {
        return this.#totalAllocatedInstances;
    }

    /**
     * [KO] 현재까지 할당된 총 인다이렉트 드로우콜 슬롯 수를 반환합니다.
     * [EN] Returns the total number of indirect draw call slots allocated so far.
     */
    get totalIndirectDrawCalls(): number {
        return this.#totalIndirectDrawCalls;
    }

    /**
     * [KO] 스캐터 타입을 위한 원시/컬링/인다이렉트 버퍼 세그먼트 영역을 할당하고 할당 정보를 반환합니다.
     * [EN] Allocates raw, culled, and indirect buffer segment regions for a scatter type and returns the allocation info.
     *
     * @param typeIdOrName -
     * [KO] 스캐터 타입의 숫자 ID 또는 문자열 이름
     * [EN] Numeric ID or string name of the scatter type
     * @param maxInstances -
     * [KO] 요청할 최대 인스턴스 개수
     * [EN] Maximum number of instances requested
     * @param renderUnitCount -
     * [KO] 할당할 인다이렉트 드로우 슬롯(렌더 유닛) 개수
     * [EN] Number of indirect draw slots (render units) to allocate
     * @param culledMultiplier -
     * [KO] 원시 인스턴스 대비 컬링 버퍼 배수 (기본값: `2`)
     * [EN] Culled buffer multiplier relative to raw instances (default: `2`)
     * @returns
     * [KO] 할당된 세그먼트 오프셋 및 용량 정보 (`ScatterBaseSegmentAllocation`)
     * [EN] Allocated segment offset and capacity information (`ScatterBaseSegmentAllocation`)
     */
    allocateBaseSegment(
        typeIdOrName: number | string,
        maxInstances: number,
        renderUnitCount: number,
        culledMultiplier: number = 2
    ): ScatterBaseSegmentAllocation {
        const alignedMax = Math.ceil(maxInstances / CULLING_WORKGROUP_SIZE) * CULLING_WORKGROUP_SIZE;
        this.ensureCapacity(this.#totalAllocatedInstances + alignedMax);

        const rawBaseOffset = this.#totalAllocatedInstances;
        const culledBaseOffset = this.#totalAllocatedCulledInstances;
        const indirectBaseOffset = this.#totalIndirectDrawCalls;

        this.#totalAllocatedInstances += alignedMax;
        this.#totalAllocatedCulledInstances += alignedMax * culledMultiplier;
        this.#totalIndirectDrawCalls += renderUnitCount;

        const typeId = typeof typeIdOrName === 'number' ? typeIdOrName : 0;
        const name = typeof typeIdOrName === 'string' ? typeIdOrName : undefined;

        return {
            typeId,
            name,
            maxInstances: alignedMax,
            rawBaseOffset,
            culledBaseOffset,
            indirectBaseOffset,
            renderUnitCount,
            instanceCount: 0
        };
    }

    /**
     * [KO] 지정된 인다이렉트 드로우 슬롯의 초기 템플릿 인자(`indexCount`, `firstIndex`, `baseVertex`, `firstInstance`)를 CPU 템플릿 버퍼에 기록합니다.
     * [EN] Writes the initial template arguments (`indexCount`, `firstIndex`, `baseVertex`, `firstInstance`) for the specified indirect draw slot into the CPU template buffer.
     *
     * @param slotIndex -
     * [KO] 기록할 인다이렉트 슬롯 인덱스
     * [EN] Indirect slot index to write
     * @param indexCount -
     * [KO] 드로우할 인덱스 개수
     * [EN] Number of indices to draw
     * @param firstIndex -
     * [KO] 시작 인덱스 오프셋 (기본값: `0`)
     * [EN] Starting index offset (default: `0`)
     * @param baseVertex -
     * [KO] 정점 버퍼 기준 오프셋 (기본값: `0`)
     * [EN] Base vertex offset (default: `0`)
     * @param firstInstance -
     * [KO] 시작 인스턴스 오프셋 (기본값: `0`)
     * [EN] First instance offset (default: `0`)
     */
    registerIndirectDrawSlot(
        slotIndex: number,
        indexCount: number,
        firstIndex: number = 0,
        baseVertex: number = 0,
        firstInstance: number = 0
    ): void {
        const base = slotIndex * DRAW_INDEXED_INDIRECT_ARGS_COUNT;
        const template = this.#indirectResetTemplate;
        template[base + 0] = indexCount;
        template[base + 1] = 0;
        template[base + 2] = firstIndex;
        template[base + 3] = baseVertex;
        template[base + 4] = firstInstance;
    }

    /**
     * [KO] CPU 인다이렉트 리셋 템플릿 데이터를 인다이렉트 GPU 버퍼 및 템플릿 GPU 버퍼로 동기화합니다.
     * [EN] Synchronizes the CPU indirect reset template data to the indirect GPU buffer and template GPU buffer.
     *
     * @param slotIndex -
     * [KO] 부분 갱신할 시작 슬롯 인덱스 (생략 시 전체 갱신)
     * [EN] Starting slot index for partial update (updates all if omitted)
     * @param slotCount -
     * [KO] 부분 갱신할 슬롯 개수 (생략 시 전체 갱신)
     * [EN] Number of slots for partial update (updates all if omitted)
     */
    syncIndirectResetTemplateToGPU(slotIndex?: number, slotCount?: number): void {
        const {gpuDevice} = this;
        const {queue} = gpuDevice;
        const indirectGPUBuffer = this.#indirectGPUBuffer;
        if (!indirectGPUBuffer) return;

        const {buffer} = this.#indirectResetTemplate;
        const indirectResetTemplateGPUBuffer = this.#indirectResetTemplateGPUBuffer;

        if (slotIndex !== undefined && slotCount !== undefined) {
            const byteOffset = slotIndex * DRAW_INDEXED_INDIRECT_ARGS_COUNT * Uint32Array.BYTES_PER_ELEMENT;
            const byteSize = slotCount * DRAW_INDEXED_INDIRECT_ARGS_COUNT * Uint32Array.BYTES_PER_ELEMENT;
            queue.writeBuffer(
                indirectGPUBuffer,
                byteOffset,
                buffer,
                byteOffset,
                byteSize
            );
            if (indirectResetTemplateGPUBuffer) {
                queue.writeBuffer(
                    indirectResetTemplateGPUBuffer,
                    byteOffset,
                    buffer,
                    byteOffset,
                    byteSize
                );
            }
        } else {
            const byteSize = this.#totalIndirectDrawCalls * DRAW_INDEXED_INDIRECT_ARGS_COUNT * Uint32Array.BYTES_PER_ELEMENT;
            if (byteSize > 0) {
                queue.writeBuffer(
                    indirectGPUBuffer,
                    0,
                    buffer,
                    0,
                    byteSize
                );
                if (indirectResetTemplateGPUBuffer) {
                    queue.writeBuffer(
                        indirectResetTemplateGPUBuffer,
                        0,
                        buffer,
                        0,
                        byteSize
                    );
                }
            }
        }
    }

    /**
     * [KO] 매 프레임 컬링 패스 실행 전에 인다이렉트 드로우 버퍼의 인스턴스 카운트들을 템플릿 상태로 초기화합니다.
     * [EN] Resets the instance counts of the indirect draw buffer to the template state prior to executing the culling pass each frame.
     *
     * @param commandEncoder -
     * [KO] 버퍼 간 복사 명령을 기록할 `GPUCommandEncoder` (생략 시 `queue.writeBuffer` 사용)
     * [EN] `GPUCommandEncoder` to record buffer-to-buffer copy commands (uses `queue.writeBuffer` if omitted)
     */
    resetMultiIndirectCommands(commandEncoder?: GPUCommandEncoder): void {
        const indirectGPUBuffer = this.#indirectGPUBuffer;
        if (this.#totalIndirectDrawCalls === 0 || !indirectGPUBuffer) return;

        const byteSize = this.#totalIndirectDrawCalls * DRAW_INDEXED_INDIRECT_ARGS_COUNT * Uint32Array.BYTES_PER_ELEMENT;

        if (commandEncoder && this.#indirectResetTemplateGPUBuffer) {
            commandEncoder.copyBufferToBuffer(
                this.#indirectResetTemplateGPUBuffer,
                0,
                indirectGPUBuffer,
                0,
                byteSize
            );
        } else {
            this.gpuDevice.queue.writeBuffer(
                indirectGPUBuffer,
                0,
                this.#indirectResetTemplate.buffer,
                0,
                byteSize
            );
        }

        this.onResetMultiIndirectCommands(commandEncoder ?? null);
    }

    /**
     * [KO] `resetMultiIndirectCommands` 실행 시 서브클래스에서 추가 인다이렉트 버퍼(예: 그림자 캐스케이드 버퍼)를 리셋하기 위한 훅 메서드입니다.
     * [EN] Hook method for subclasses to reset additional indirect buffers (e.g., shadow cascade buffers) when `resetMultiIndirectCommands` runs.
     *
     * @param commandEncoder -
     * [KO] 전달된 `GPUCommandEncoder` 또는 `null`
     * [EN] Passed `GPUCommandEncoder` or `null`
     */
    onResetMultiIndirectCommands(commandEncoder: GPUCommandEncoder | null): void {
    }

    /**
     * [KO] 할당된 원시/컬링 인스턴스 카운터 및 인다이렉트 드로우 카운터를 `0`으로 초기화합니다.
     * [EN] Resets the allocated raw/culled instance counters and indirect draw counter to `0`.
     */
    clearBaseAllocations(): void {
        this.#totalAllocatedInstances = 0;
        this.#totalAllocatedCulledInstances = 0;
        this.#totalIndirectDrawCalls = 0;
    }

    /**
     * [KO] 요청된 인스턴스 수용량을 충족하도록 메가 버퍼 크기를 점검하고, 부족할 경우 GPU 버퍼를 확장 재할당합니다.
     * [EN] Checks the mega buffer size to satisfy the requested instance capacity, expanding and reallocating GPU buffers if insufficient.
     *
     * @param requiredCapacity -
     * [KO] 필요한 총 인스턴스 수용량
     * [EN] Required total instance capacity
     * @returns
     * [KO] 버퍼 확장이 실제로 수행되었는지 여부 (`true`: 재할당됨, `false`: 기존 용량 유지)
     * [EN] Whether buffer expansion was actually performed (`true`: reallocated, `false`: kept existing capacity)
     */
    ensureCapacity(requiredCapacity: number): boolean {
        if (requiredCapacity <= this.#instanceCapacity) {
            return false;
        }

        const {gpuDevice} = this;
        const maxBufferSize = gpuDevice.limits?.maxBufferSize ?? 2147483648;
        const maxSafeInstanceCapacity = Math.floor(maxBufferSize / (this.#strideBytes * 32));

        let newCapacity = this.#instanceCapacity;
        while (newCapacity < requiredCapacity) {
            newCapacity = Math.ceil((newCapacity * 2) / CULLING_WORKGROUP_SIZE) * CULLING_WORKGROUP_SIZE;
        }

        if (newCapacity > maxSafeInstanceCapacity) {
            console.warn(
                `[${this.constructor.name}] Requested capacity (${newCapacity}) exceeds safe limit (${maxSafeInstanceCapacity}) for WebGPU maxBufferSize (${maxBufferSize} bytes). Clamping to safe limit.`
            );
            newCapacity = Math.floor(maxSafeInstanceCapacity / CULLING_WORKGROUP_SIZE) * CULLING_WORKGROUP_SIZE;
        }

        if (newCapacity <= this.#instanceCapacity) {
            return false;
        }

        this.#instanceCapacity = newCapacity;

        const {STORAGE, COPY_DST} = GPUBufferUsage;
        this.#rawGPUBuffer.destroy();
        this.#rawGPUBuffer = gpuDevice.createBuffer({
            label: `${this.constructor.name}_RawInstances`,
            size: newCapacity * this.#strideBytes,
            usage: STORAGE | COPY_DST,
        });

        this.onResizeBuffers(newCapacity);

        this.#onRecreated?.();
        return true;
    }

    /**
     * [KO] 메가 버퍼가 보유한 모든 기본 및 파생 GPU 버퍼들을 파기합니다.
     * [EN] Destroys all base and derived GPU buffers held by the mega buffer.
     */
    destroy(): void {
        this.#rawGPUBuffer.destroy();
        this.#culledGPUBuffer?.destroy();
        this.#indirectGPUBuffer.destroy();
        this.#indirectResetTemplateGPUBuffer.destroy();
        this.#typeParamsGPUBuffer?.destroy();

        this.#rawGPUBuffer = null;
        this.#culledGPUBuffer = null;
        this.#indirectGPUBuffer = null;
        this.#indirectResetTemplateGPUBuffer = null;
        this.#typeParamsGPUBuffer = null;

        this.invalidateUnifiedCullingBindGroup();

        this.onDestroy();
    }

    /**
     * [KO] 통합 컬링 바인드 그룹 캐시를 무효화합니다.
     * [EN] Invalidates the unified culling bind group cache.
     */
    abstract invalidateUnifiedCullingBindGroup(): void;

    /**
     * [KO] 수용량 확장 시 서브클래스 전용 GPU 버퍼들을 재할당하기 위한 추상 훅 메서드입니다.
     * [EN] Abstract hook method for reallocating subclass-specific GPU buffers upon capacity expansion.
     *
     * @param newCapacity -
     * [KO] 확장된 새 인스턴스 수용량
     * [EN] Newly expanded instance capacity
     */
    abstract onResizeBuffers(newCapacity: number): void;

    /**
     * [KO] 메가 버퍼 파기 시 서브클래스 전용 리소스를 정리하기 위한 추상 훅 메서드입니다.
     * [EN] Abstract hook method for cleaning up subclass-specific resources when destroying the mega buffer.
     */
    abstract onDestroy(): void;

    #initBaseBuffers(): void {
        const {gpuDevice} = this;
        const {STORAGE, COPY_DST, UNIFORM, INDIRECT, COPY_SRC} = GPUBufferUsage;
        const className = this.constructor.name;

        const rawByteSize = Math.max(this.#instanceCapacity * this.#strideBytes, 64);
        const typeParamsByteSize = this.#maxTypes * this.#typeParamFloats * Float32Array.BYTES_PER_ELEMENT;

        this.#rawGPUBuffer = gpuDevice.createBuffer({
            label: `${className}_RawInstances`,
            size: rawByteSize,
            usage: STORAGE | COPY_DST,
        });

        if (typeParamsByteSize > 0) {
            this.#typeParamsGPUBuffer = gpuDevice.createBuffer({
                label: `${className}_TypeParams`,
                size: typeParamsByteSize,
                usage: STORAGE | UNIFORM | COPY_DST,
            });
        }

        const indirectByteSize = Math.max(
            this.#maxRenderUnits * DRAW_INDEXED_INDIRECT_ARGS_COUNT * Uint32Array.BYTES_PER_ELEMENT,
            64
        );

        this.#indirectGPUBuffer = gpuDevice.createBuffer({
            label: `${className}_Indirect_Main`,
            size: indirectByteSize,
            usage: STORAGE | INDIRECT | COPY_DST,
        });

        this.#indirectResetTemplateGPUBuffer = gpuDevice.createBuffer({
            label: `${className}_Indirect_Template`,
            size: indirectByteSize,
            usage: COPY_SRC | COPY_DST,
        });
    }
}

Object.freeze(AScatterMegaBuffer);
export default AScatterMegaBuffer;
